"""`results/day8/day8.md`, generated from the JSON the harness wrote.

Nothing here is hand-edited, for the third day running and for the reason Day 6
Phase 1 found the hard way: `results/day5/retrieval.md` was a generated document
whose generator carried `122` as a literal, so re-verifying the golden set
silently made a *published* document wrong. Every number below is read from the
artifact that measured it, and a missing key raises rather than defaulting.

The prose around the numbers is written here rather than in the artifact, and it
is written to be true of any run: the sentences say what the columns mean, and the
figures come from the file.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from regops_evals.gate_agent import dig


def _pc(part, whole) -> str:
    return f"{part}/{whole}" if whole else "--"


def _head(d: dict) -> str:
    return f"""# Day 8 — agent evaluation, and a gate that can actually fail

Generated by `python -m regops_evals.agentreport`. Do not edit by hand.

Model `{d["model"]}` · judge `{d.get("judge", {}).get("supervisor", {}).get("model", "n/a")}` ·
{d["n_tasks"]} tasks derived from `golden/v1` · {len(d["arms"])} architectures ·
traced: {d["traced"]} · produced {d["produced_at"]} in {d["wall_s"]}s

Prompt hash `{d["prompt_hash"][:12]}` over {len(d["prompts"])} registered prompts ·
task file `{d["tasks_sha"][:12]}`. CI recomputes both and fails on a mismatch, which is
how *"change a prompt, push, and CI tells you"* works on a machine with no GPU in CI.
"""


def _tasks(d: dict) -> str:
    return """
## What the tasks are, and where their expectations come from

Thirty end-to-end tasks, **derived from the golden set rather than rewritten from
it**: each carries the `golden_id` it came from, its `gold_doc_ids` come out of
`gold_spans`, and `must_abstain` is `query_type == "negative"`. A change to
`golden/v1` therefore shows up as a failing test rather than as silent drift
(`evals/tests/test_tasks.py`).

`min_tool_calls` is supplied by the data too — one search plus one read per
distinct gold document, and the distinct-document count is a measured property of
the taxonomy (ADR-018): 1 for `factual_lookup` and `temporal`, 2 for `multi_hop`,
2 or 3 for `comparative`, 0 for the negatives. Trajectory efficiency is therefore
a ratio against a principled floor rather than against a guess.

There is no version task: `diff_versions` is unreachable from the supervisor by
design (ADR-028) and this corpus has no genuine multi-version document
(`regdocs-mcp` ADR-004). A task nothing can pass measures the task set.
"""


def _headline(d: dict) -> str:
    rows = [
        "| architecture | task success | gold read | cited resolvable | abstained right |"
        " within budget | p50 s | tokens | unresolvable |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for arm, m in d["metrics"].items():
        s = m["success"]
        rows.append(
            f"| `{arm}` | **{_pc(s['composite']['passed'], s['composite']['n'])}** "
            f"| {_pc(s['retrieved_gold']['passed'], s['retrieved_gold']['n'])} "
            f"| {_pc(s['cited_resolvable']['passed'], s['cited_resolvable']['n'])} "
            f"| {_pc(s['abstained_correctly']['passed'], s['abstained_correctly']['n'])} "
            f"| {_pc(s['within_budget']['passed'], s['within_budget']['n'])} "
            f"| {m['latency']['p50_s']:.1f} | {m['cost']['tokens']:,} "
            f"| {m['citations']['unresolvable']} |"
        )
    return f"""
## The five metrics, over three architectures

**Task success is four mechanical outcomes and the composite that requires all
four.** Reported both ways: the composite is what the gate needs, the four are
what a person needs in order to fix anything. Every one is derived from the golden
set — no judge is involved in any column below.

{chr(10).join(rows)}

Only `{d["gated_arm"]}` is gated. The other two are measured so that Day 7's
comparison stays alive as a regression surface for free; gating all three triples
the ways a build can fail for reasons nobody is working on.
"""


def _abstention(d: dict) -> str:
    rows = [
        "| architecture | false abstention (of the 25 answerable) |"
        " false answer (of the 5 unanswerable) |",
        "|---|---|---|",
    ]
    for arm, m in d["metrics"].items():
        a = m["abstention"]
        rows.append(
            f"| `{arm}` | {_pc(a['false_abstention']['count'], a['false_abstention']['n'])} "
            f"| {_pc(a['false_answer']['count'], a['false_answer']['n'])} |"
        )
    return f"""
### Abstention is two rates, never one

ADR-021's point, applied to agents: refusing a question you have the clause for
and answering one the corpus cannot answer are different failures, and a single
"accuracy" averages them into a number that describes neither. The second column
is the dangerous direction.

{chr(10).join(rows)}

Detection is textual (`agenteval.REFUSAL`) and that is the weakest mechanism in
this module. It is kept mechanical anyway: the alternative is asking the judge,
and then the gate depends on a model's opinion.
"""


def _trajectory(d: dict) -> str:
    rows = [
        "| architecture | tool-call recall | precision | efficiency | tool calls |"
        " min possible | errors |",
        "|---|---|---|---|---|---|---|",
    ]
    for arm, m in d["metrics"].items():
        t, tc = m["trajectory"], m["tool_calls"]
        rows.append(
            f"| `{arm}` | {tc['recall_mean']} | {tc['precision_mean']} "
            f"| {t['efficiency_mean']} | {t['actual_total']} | {t['min_total']} "
            f"| {tc['errors']} |"
        )
    return f"""
### Trajectory: what it read, and how much of it had to be read

**Recall is "did it read the gold document"; precision is "what fraction of what
it read was gold".** Reading, not retrieving — a `doc_id` that appeared in a
search result was offered to the agent, not used by it, and crediting that would
measure BM25 rather than the agent (`record.documents_read`).

{chr(10).join(rows)}

Precision is reported and not gated. A supervisor reads five sections per search
by construction (`workers.READ_N`), so its precision is a property of the
retriever's fixed shape rather than of a decision it made per task — and a metric
that punishes breadth would gate the architecture instead of the regression. The
same fixed shape caps its efficiency: `min_tool_calls` is 2 for most tasks and the
graph always spends 6, which is a finding about the retriever rather than a
failure of the run.
"""


def _judge(d: dict) -> str:
    if not d.get("judge"):
        return ""
    rows = [
        "| architecture | supported | complete | cited correctly | all three | judged |",
        "|---|---|---|---|---|---|",
    ]
    for arm, j in d["judge"].items():
        a = j["axes"]
        rows.append(
            f"| `{arm}` | {_pc(a['supported']['passed'], a['supported']['n'])} "
            f"| {_pc(a['complete']['passed'], a['complete']['n'])} "
            f"| {_pc(a['cited_correctly']['passed'], a['cited_correctly']['n'])} "
            f"| {_pc(j['all_three']['passed'], j['all_three']['n'])} | {j['judged']} |"
        )
    per_call = next(iter(d["judge"].values())).get("seconds_per_call")
    return f"""
## Layer 3, finally: is the prose supported by what it cited?

Deferred on Day 6 (no judge) and again on Day 7 (layer 2 was already at its
ceiling, so a judge would have measured a rate with no room to move). Three axes,
scored separately, because they fail for different reasons — an answer can be
perfectly supported and answer a third of the question, and a composite hides
exactly that.

{chr(10).join(rows)}

`qwen3.8`, not the model that wrote the answers (ADR-017: the checker is not the
writer). {per_call}s per call, so thirty tasks is about two minutes. Abstentions and
negatives are skipped rather than scored: an abstention has no claims to support.

**The judge does not gate.** Its verdicts are an uncalibrated model's opinion
until `golden/judge_calibration/` says otherwise, and a build that fails on that
fails for a reason nobody can audit.
"""


def _calibration(agreement: dict | None) -> str:
    if agreement is None:
        return ""
    if not agreement.get("calibrated"):
        return f"""
### Judge calibration

**The judge is uncalibrated.** {agreement["selected"]} verdicts were selected for
hand-scoring — contested ones first, where the judge and the mechanical checks
reach opposite verdicts — and {agreement["scored"]} have been scored. No agreement
rate is quoted, because an estimated one looks exactly like a measured one. This
was written into the plan before the work started (Phase 4), and the alternative
was to guess.
"""
    rows = ["| axis | agree | judge harsher | judge more lenient |", "|---|---|---|---|"]
    for axis, a in agreement["axes"].items():
        rows.append(
            f"| {axis} | **{_pc(a['agree'], a['n'])}** | {a['judge_harsher']} "
            f"| {a['judge_more_lenient']} |"
        )
    return f"""
### Judge calibration — {agreement["scored"]} hand-scored examples

{chr(10).join(rows)}

{agreement["sample_note"]} Selection put the contested rows first
({agreement.get("contested_scored", 0)} of {agreement["scored"]} scored items), so
this is a *lower bound* on agreement rather than a representative rate — which is
the useful direction to be wrong in.

The scores live in `golden/judge_calibration/`, never in `golden/v1`, and are
never used to relabel a golden item. ADR-017 draws that line and an agreement
study that quietly promoted twenty items would dissolve the boundary it was
measuring against.
"""


def _determinism(det: dict | None) -> str:
    if det is None:
        return ""
    gated = det["gated_arm"]
    rows = [
        "| architecture | items identical | tokens, run 1 | run 2 | p50 drift |",
        "|---|---|---|---|---|",
    ]
    for arm, r in det["arms"].items():
        n, moved = r["items"], len(r["differing"])
        t0, t1 = r["tokens"]
        p0, p1 = r["p50_s"]
        drift = f"{(p1 - p0) / p0:+.1%}" if p0 else "--"
        rows.append(f"| `{arm}` | **{n - moved}/{n}** | {t0:,} | {t1:,} | {drift} |")
    g = det["arms"][gated]
    verdict = (
        f"**identical on every one of the {len(g['compared_fields'])} compared fields**"
        if g["identical"]
        else f"**{len(g['differing'])} of {g['items']} items moved** — which is a bug, not a cost"
    )
    return f"""
## Did instrumenting the agents change them? And which arm can be gated exactly?

Risk 5 of the plan. Recording every tool call is bookkeeping in the hot path, and
"it cannot plausibly change an answer" is the kind of claim this project has been
wrong about before — F15 was a shared DuckDB connection handing one caller's rows
to another, and nothing about that was plausible either. So two runs, two
processes, compared field by field with the recorder and the tracer attached.

{chr(10).join(rows)}

For `{gated}` the answer is {verdict}. **That zero is what licenses an exact
gate.** The prep plan's ">5% drop" threshold is about fifty times looser than this
pipeline needs, and a 5% band would hide a single regressed task — exactly the
resolution the determinism work (ADR-022 here, ADR-008 in `regdocs-mcp`) was paid
for. Latency is deliberately not compared: it is a fact about Ollama's queue.

**And the comparison answers a question nobody asked.** Day 6's ReAct agent is
*not* reproducible across processes — its answers, its step counts, its tool calls
and on one task whether it succeeded at all. Both arms run at temperature 0. The
graph asks for a small typed answer through constrained decoding on every call;
the ReAct agent generates free-form text over the full vocabulary and lets the
framework parse it. That is the likely cause and it is a hypothesis rather than a
measurement. What *is* measured is that only one of these two architectures can be
gated exactly, and it is the one the gate gates — which turns Day 8's scoping
decision into a technical constraint rather than a preference.
"""


def _gate(d: dict) -> str:
    return """
## The gate

CI has no GPU and this account has no self-hosted runner (`gh api
.../actions/runners` returns `total_count: 0`), so the eval cannot run where the
gate runs. The tempting move is a CI job that skips when there is no model, which
is a green check mark that proves nothing. Instead the eval runs locally and
commits `results/day8/eval.json`, and **CI gates the artifact**:

1. **Staleness.** The artifact records a hash over every prompt and system message
   it was produced from, plus a hash of the task file. CI recomputes both. *A
   prompt changed and pushed without a re-run fails the build.* CI cannot measure
   the change; it can refuse to believe a number measured before it.
2. **Comparison.** Every mechanical metric must be at least as good as
   `baseline.json` — **exactly**, not within a band, because the noise floor was
   measured at zero. Latency is the one exception, at 25% against a measured 6.5%
   spread.
3. **Replay.** `agents/tests/test_replay.py` drives the whole graph over 44
   recorded MCP results with a scripted model: routing, the reroute, the fan-out,
   the ceilings. It gates structure, not quality, and says so.

The hash is over the prompt **strings**, not the files. Hashing `workers.py` would
turn every docstring edit red, and a gate that is red for reasons nobody is
working on gets switched off within a week.
"""


def _can_fail(base: dict, bad: dict | None) -> str:
    """The gate rejecting a deliberately degraded prompt, from the two artifacts."""
    if bad is None:
        return ""
    b = base["metrics"]["supervisor"]
    x = bad["metrics"][bad.get("gated_arm", "supervisor")]

    def row(label, path):
        get = lambda m: dig(m, path)  # noqa: E731
        return f"| {label} | {get(b)} | {get(x)} |"

    return f"""
### Proof that it can fail

A gate never observed failing is a gate nobody knows the polarity of. Three
sentences were deleted from `EXTRACT_PROMPT` — the ones that explain how to read a
citation out of an excerpt header — and the build was watched going red twice and
green again. Full transcript, with exit codes:
[`gate-can-fail.txt`](gate-can-fail.txt).

First it failed **stale**, before any re-measurement: the committed numbers were
produced against a prompt that no longer existed, and the gate named which one
(`workers.EXTRACT_PROMPT`, `{base["prompt_hash"][:12]}` → `{bad["prompt_hash"][:12]}`).
Then the eval was re-run and it failed again, on the numbers:

| metric | baseline | degraded |
|---|---|---|
{row("task success (all four)", ("success", "composite", "passed"))}
{row("abstained correctly", ("success", "abstained_correctly", "passed"))}
{row("answered a question the corpus cannot", ("abstention", "false_answer", "count"))}
{row("gold documents read", ("success", "retrieved_gold", "passed"))}
{row("resolvable citations", ("citations", "resolvable"))}

The last two rows are why the composite exists. The degraded prompt read **more**
gold documents and produced **more** resolvable citations, and it was still worse:
it went from answering 1 of the 5 unanswerable questions to answering 3. A single
headline metric would have shown this change as an improvement.

"""


def render(
    d: dict, agreement: dict | None = None, det: dict | None = None, degraded: dict | None = None
) -> str:
    """The whole document, normalised.

    One trailing newline and no trailing spaces, because the repo's pre-commit
    hooks fix both — and a generated file whose own hooks rewrite it is a file that
    is dirty every time it is regenerated, which is a slow way to stop trusting the
    generator.
    """
    body = "".join(
        [
            _head(d),
            _tasks(d),
            _headline(d),
            _abstention(d),
            _trajectory(d),
            _judge(d),
            _calibration(agreement),
            _determinism(det),
            _gate(d),
            _can_fail(d, degraded),
        ]
    )
    return "\n".join(ln.rstrip() for ln in body.splitlines()).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--eval", type=Path, default=Path("results/day8/eval.json"))
    ap.add_argument(
        "--agreement", type=Path, default=Path("golden/judge_calibration/agreement.json")
    )
    ap.add_argument("--determinism", type=Path, default=Path("results/day8/determinism.json"))
    ap.add_argument("--degraded", type=Path, default=Path("results/day8/eval-degraded.json"))
    ap.add_argument("--out", type=Path, default=Path("results/day8/day8.md"))
    a = ap.parse_args(argv)

    d = json.loads(a.eval.read_text())
    agreement = json.loads(a.agreement.read_text()) if a.agreement.exists() else None
    det = json.loads(a.determinism.read_text()) if a.determinism.exists() else None
    bad = json.loads(a.degraded.read_text()) if a.degraded.exists() else None
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(render(d, agreement, det, bad))
    print(f"-> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
